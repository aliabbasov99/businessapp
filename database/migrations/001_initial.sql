-- Amounts are integer qəpik. The bound guarantees lossless JSON/JavaScript numbers.
CREATE DOMAIN money_minor AS bigint CHECK (VALUE BETWEEN -9007199254740991 AND 9007199254740991);
CREATE DOMAIN business_type AS text CHECK (VALUE IN ('restaurant', 'retail', 'accounting'));

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  name text NOT NULL CHECK (length(trim(name)) > 0),
  email text NOT NULL UNIQUE,
  phone text
);
CREATE TABLE businesses (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  name text NOT NULL, type business_type NOT NULL
);
CREATE TABLE memberships (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  user_id integer NOT NULL REFERENCES users,
  business_id integer NOT NULL REFERENCES businesses,
  role text NOT NULL CHECK (role IN ('owner', 'manager')),
  UNIQUE (user_id, business_id)
);
CREATE TABLE branches (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  business_id integer NOT NULL REFERENCES businesses,
  name text NOT NULL, type business_type NOT NULL,
  UNIQUE (id, business_id)
);
CREATE TABLE systems (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  business_id integer NOT NULL REFERENCES businesses,
  type text NOT NULL CHECK (type IN ('restaurant_pos', 'retail_inventory', 'accounting')),
  UNIQUE (business_id, type)
);
CREATE TABLE sales (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  branch_id integer NOT NULL REFERENCES branches,
  receipt_number integer NOT NULL CHECK (receipt_number > 0),
  occurred_at timestamptz NOT NULL,
  amount_minor money_minor NOT NULL,
  payment_method text NOT NULL CHECK (payment_method IN ('card', 'cash')),
  type text NOT NULL CHECK (type IN ('sale', 'refund')),
  CHECK ((type = 'sale' AND amount_minor >= 0) OR (type = 'refund' AND amount_minor < 0)),
  UNIQUE (branch_id, receipt_number)
);
CREATE INDEX sales_branch_date_idx ON sales (branch_id, occurred_at DESC);
CREATE TABLE products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  business_id integer NOT NULL REFERENCES businesses,
  name text NOT NULL, code text NOT NULL,
  unit text NOT NULL CHECK (unit IN ('kg', 'liter', 'box', 'piece')),
  cost_price_minor money_minor NOT NULL CHECK (cost_price_minor >= 0),
  sale_price_minor money_minor NOT NULL CHECK (sale_price_minor >= 0),
  UNIQUE (business_id, code), UNIQUE (id, business_id)
);
CREATE TABLE stock_balances (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  business_id integer NOT NULL REFERENCES businesses,
  branch_id integer NOT NULL, product_id integer NOT NULL,
  quantity numeric(18,3) NOT NULL CHECK (quantity >= 0),
  FOREIGN KEY (branch_id, business_id) REFERENCES branches (id, business_id),
  FOREIGN KEY (product_id, business_id) REFERENCES products (id, business_id),
  UNIQUE (branch_id, product_id)
);
CREATE TABLE suppliers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  business_id integer NOT NULL REFERENCES businesses,
  name text NOT NULL, tax_id text NOT NULL, phone text NOT NULL,
  balance_minor money_minor NOT NULL, deposit_minor money_minor NOT NULL,
  UNIQUE (business_id, tax_id)
);
CREATE TABLE cash_transactions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  branch_id integer NOT NULL REFERENCES branches,
  description text NOT NULL, amount_minor money_minor NOT NULL,
  account text NOT NULL CHECK (account IN ('bank', 'cash')),
  occurred_at timestamptz NOT NULL
);
CREATE INDEX cash_branch_date_idx ON cash_transactions (branch_id, occurred_at DESC);
CREATE TABLE events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  business_id integer NOT NULL REFERENCES businesses,
  branch_id integer,
  type text NOT NULL CHECK (type IN ('receipt_cancelled', 'discount_applied', 'daily_report_ready')),
  occurred_at timestamptz NOT NULL,
  receipt_number integer CHECK (receipt_number > 0),
  amount_minor money_minor, reason text,
  discount_percent numeric(7,4) CHECK (discount_percent BETWEEN 0 AND 100),
  FOREIGN KEY (branch_id, business_id) REFERENCES branches (id, business_id),
  UNIQUE (id, business_id),
  CHECK (
    (type = 'receipt_cancelled' AND branch_id IS NOT NULL AND receipt_number IS NOT NULL AND amount_minor IS NOT NULL AND reason IS NOT NULL AND discount_percent IS NULL)
    OR (type = 'discount_applied' AND branch_id IS NOT NULL AND receipt_number IS NOT NULL AND discount_percent IS NOT NULL AND amount_minor IS NULL AND reason IS NULL)
    OR (type = 'daily_report_ready' AND branch_id IS NULL AND receipt_number IS NULL AND amount_minor IS NULL AND reason IS NULL AND discount_percent IS NULL)
  )
);
CREATE INDEX events_business_date_idx ON events (business_id, occurred_at DESC);
CREATE TABLE notifications (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  user_id integer NOT NULL, business_id integer NOT NULL, event_id integer NOT NULL,
  created_at timestamptz NOT NULL, read_at timestamptz,
  FOREIGN KEY (user_id, business_id) REFERENCES memberships (user_id, business_id),
  FOREIGN KEY (event_id, business_id) REFERENCES events (id, business_id),
  UNIQUE (user_id, event_id), CHECK (read_at IS NULL OR read_at >= created_at)
);
CREATE INDEX notifications_user_date_idx ON notifications (user_id, created_at DESC);
CREATE TABLE app_metadata (
  id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  schema_version integer NOT NULL CHECK (schema_version > 0),
  active_user_id integer NOT NULL, active_business_id integer NOT NULL,
  currency char(3) NOT NULL, time_zone text NOT NULL, as_of timestamptz NOT NULL,
  FOREIGN KEY (active_user_id, active_business_id) REFERENCES memberships (user_id, business_id)
);
CREATE TABLE report_periods (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  code text NOT NULL UNIQUE CHECK (code IN ('week', 'month', 'year'))
);
CREATE TABLE report_buckets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  period_id integer NOT NULL REFERENCES report_periods,
  starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL,
  CHECK (starts_at < ends_at), UNIQUE (period_id, starts_at), UNIQUE (id, period_id)
);

-- Imported aggregate snapshots: the sample receipt list is not a complete ledger.
CREATE TABLE overview_snapshots (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  business_id integer NOT NULL REFERENCES businesses,
  starts_at timestamptz NOT NULL, as_of timestamptz NOT NULL,
  sales_revenue_minor money_minor NOT NULL,
  sales_cost_minor money_minor NOT NULL,
  sales_revenue_change_percent numeric(12,4) NOT NULL,
  sales_cost_change_percent numeric(12,4) NOT NULL,
  sales_profit_change_percent numeric(12,4) NOT NULL,
  inventory_quantity numeric(18,3) NOT NULL,
  inventory_cost_minor money_minor NOT NULL,
  inventory_retail_minor money_minor NOT NULL,
  inventory_quantity_change_percent numeric(12,4) NOT NULL,
  inventory_cost_change_percent numeric(12,4) NOT NULL,
  inventory_retail_change_percent numeric(12,4) NOT NULL,
  suppliers_debt_minor money_minor NOT NULL,
  suppliers_purchases_minor money_minor NOT NULL,
  suppliers_interest_minor money_minor NOT NULL,
  suppliers_debt_change_percent numeric(12,4) NOT NULL,
  suppliers_purchases_change_percent numeric(12,4) NOT NULL,
  suppliers_interest_change_percent numeric(12,4) NOT NULL,
  cash_inflow_minor money_minor NOT NULL,
  cash_outflow_minor money_minor NOT NULL,
  cash_balance_change_percent numeric(12,4) NOT NULL,
  cash_inflow_change_percent numeric(12,4) NOT NULL,
  cash_outflow_change_percent numeric(12,4) NOT NULL,
  CHECK (starts_at <= as_of), UNIQUE (business_id, starts_at, as_of)
);

CREATE TABLE sales_datasets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  business_id integer NOT NULL REFERENCES businesses,
  period_id integer NOT NULL REFERENCES report_periods,
  branch_id integer,
  change_percent numeric(12,4) NOT NULL,
  FOREIGN KEY (branch_id, business_id) REFERENCES branches (id, business_id),
  UNIQUE NULLS NOT DISTINCT (business_id, branch_id, period_id),
  UNIQUE (id, period_id)
);
CREATE TABLE sales_points (
  dataset_id integer NOT NULL, period_id integer NOT NULL, bucket_id integer NOT NULL,
  customer_count integer NOT NULL CHECK (customer_count >= 0),
  revenue_minor money_minor NOT NULL,
  cost_minor money_minor NOT NULL,
  PRIMARY KEY (dataset_id, bucket_id),
  FOREIGN KEY (dataset_id, period_id) REFERENCES sales_datasets (id, period_id),
  FOREIGN KEY (bucket_id, period_id) REFERENCES report_buckets (id, period_id)
);

CREATE TABLE inventory_datasets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  business_id integer NOT NULL REFERENCES businesses,
  period_id integer NOT NULL REFERENCES report_periods,
  UNIQUE (business_id, period_id),
  UNIQUE (id, period_id)
);
CREATE TABLE inventory_points (
  dataset_id integer NOT NULL, period_id integer NOT NULL, bucket_id integer NOT NULL,
  sales_minor money_minor NOT NULL,
  cost_minor money_minor NOT NULL,
  quantity numeric(18,3) NOT NULL CHECK (quantity >= 0),
  unsold_amount_minor money_minor NOT NULL,
  unsold_quantity numeric(18,3) NOT NULL CHECK (unsold_quantity >= 0),
  PRIMARY KEY (dataset_id, bucket_id),
  FOREIGN KEY (dataset_id, period_id) REFERENCES inventory_datasets (id, period_id),
  FOREIGN KEY (bucket_id, period_id) REFERENCES report_buckets (id, period_id)
);

CREATE TABLE cash_datasets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  business_id integer NOT NULL REFERENCES businesses,
  period_id integer NOT NULL REFERENCES report_periods,
  UNIQUE (business_id, period_id),
  UNIQUE (id, period_id)
);
CREATE TABLE cash_points (
  dataset_id integer NOT NULL, period_id integer NOT NULL, bucket_id integer NOT NULL,
  balance_minor money_minor NOT NULL,
  outflow_minor money_minor NOT NULL,
  inflow_minor money_minor NOT NULL,
  PRIMARY KEY (dataset_id, bucket_id),
  FOREIGN KEY (dataset_id, period_id) REFERENCES cash_datasets (id, period_id),
  FOREIGN KEY (bucket_id, period_id) REFERENCES report_buckets (id, period_id)
);

CREATE TABLE company_datasets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  business_id integer NOT NULL REFERENCES businesses,
  period_id integer NOT NULL REFERENCES report_periods,
  UNIQUE (business_id, period_id),
  UNIQUE (id, period_id)
);
CREATE TABLE company_points (
  dataset_id integer NOT NULL, period_id integer NOT NULL, bucket_id integer NOT NULL,
  balance_minor money_minor NOT NULL,
  purchases_minor money_minor NOT NULL,
  payments_minor money_minor NOT NULL,
  PRIMARY KEY (dataset_id, bucket_id),
  FOREIGN KEY (dataset_id, period_id) REFERENCES company_datasets (id, period_id),
  FOREIGN KEY (bucket_id, period_id) REFERENCES report_buckets (id, period_id)
);
